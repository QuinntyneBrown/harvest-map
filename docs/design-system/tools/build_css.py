#!/usr/bin/env python3
"""Build tokens.css and components.css for the Harvest Map design system from the mock assets.

    python docs/design-system/tools/build_css.py

tokens.css   = docs/mocks/assets/tokens.css + the motion/size tokens the extraction added.
components.css = docs/mocks/assets/ui.css + harvest.css, with raw durations and off-grid
                 sizes replaced by tokens (every replacement is logged as drift in README.md).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MOCKS = ROOT.parent / "mocks" / "assets"

EXTRA_TOKENS = """
  /* ---------- Added during extraction (Harvest Map) ---------------------- */
  --duration-loop-fast: 800ms;   /* spinner revolution */
  --duration-loop: 1.6s;         /* pulse, shimmer, indeterminate progress */
  --duration-loop-slow: 2.4s;    /* map pin ripple */
  --duration-ambient: 24s;       /* hero field fallback gradient turn */
  --stagger: 40ms;               /* delay between list items entering */
  --size-dot: 0.5rem;            /* status dots, legend marks */
  --size-pin: 0.75rem;           /* map pin core */
  --size-badge: 1.5rem;          /* badge and tag min height (snapped from 22px) */
"""

REPLACEMENTS = [
    ("animation: spin 0.8s linear infinite", "animation: spin var(--duration-loop-fast) linear infinite"),
    ("1.4s var(--ease-standard) infinite", "var(--duration-loop) var(--ease-standard) infinite"),
    ("1.6s var(--ease-standard) infinite", "var(--duration-loop) var(--ease-standard) infinite"),
    ("pin-pulse 2.4s", "pin-pulse var(--duration-loop-slow)"),
    ("calc(var(--i, 0) * 180ms)", "calc(var(--i, 0) * var(--stagger) * 4.5)"),
    ("calc(var(--i, 0) * 40ms)", "calc(var(--i, 0) * var(--stagger))"),
    ("field-turn 24s linear infinite", "field-turn var(--duration-ambient) linear infinite"),
    ("min-height: 1.375rem", "min-height: var(--size-badge)"),
    ("min-width: 1.375rem", "min-width: var(--size-badge)"),
    ("width: 0.375rem; height: 0.375rem;", "width: var(--size-dot); height: var(--size-dot);"),
    ("width: 0.625rem; height: 0.625rem;", "width: var(--size-dot); height: var(--size-dot);"),
    ("width: 0.75rem; height: 0.75rem; border-radius: 50%; background: var(--color-accent)", "width: var(--size-pin); height: var(--size-pin); border-radius: 50%; background: var(--color-accent)"),
    ("border-radius: 2px 2px 0 0", "border-radius: var(--radius-xs) var(--radius-xs) 0 0"),
    ("mask-image: linear-gradient(to bottom, black 55%, transparent)", "mask-image: linear-gradient(to bottom, currentColor 55%, transparent)"),
    ("background: color-mix(in oklch, var(--color-warning-bg) 70%, var(--color-bg-surface))", "background: var(--color-warning-bg)"),
]

HEADER = """/* ==========================================================================
   components.css — Harvest Map component library.
   Generated by docs/design-system/tools/build_css.py from the mocks' ui.css
   and harvest.css. Every value comes from tokens/tokens.css; every component
   has real pseudo-class states and matching data-state hooks.
   Do not edit by hand: edit the mock assets or this build script.
   ========================================================================== */
"""


def main() -> int:
    tokens = (MOCKS / "tokens.css").read_text(encoding="utf-8")
    anchor = "  color-scheme: light;\n}"
    assert anchor in tokens
    tokens = tokens.replace(anchor, EXTRA_TOKENS + "\n" + anchor, 1)
    tokens = tokens.replace("    --duration-deliberate: 0.01ms;\n", "    --duration-deliberate: 0.01ms;\n    --duration-loop-fast: 0.01ms;\n    --duration-loop: 0.01ms;\n    --duration-loop-slow: 0.01ms;\n    --duration-ambient: 0.01ms;\n    --stagger: 0ms;\n", 1)
    (ROOT / "tokens" / "tokens.css").write_text(tokens, encoding="utf-8")

    css = (MOCKS / "ui.css").read_text(encoding="utf-8") + "\n" + (MOCKS / "harvest.css").read_text(encoding="utf-8")
    for old, new in REPLACEMENTS:
        if old not in css:
            raise SystemExit(f"replacement not found: {old}")
        css = css.replace(old, new)
    css += """
/* ---------- Added by the design system (not yet in mocks) ----------------- */
.divider { border: 0; border-top: var(--border-width-hairline) solid var(--color-border-default); margin: var(--space-4) 0; }
"""
    (ROOT / "assets" / "components.css").write_text(HEADER + css, encoding="utf-8")
    print("tokens.css and components.css written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
